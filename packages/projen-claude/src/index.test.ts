import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import * as path from 'node:path'

import { describe, expect, test } from '@langri-sha/vitest'
import { Project } from 'projen'
import { synthSnapshot } from 'projen/lib/util/synth'

import { Claude, type ClaudeOptions } from './index'

const synth = (options?: ClaudeOptions) => {
  const project = new Project({
    name: 'test-project',
  })

  new Claude(project, options)

  return synthSnapshot(project)
}

const settings = (options?: ClaudeOptions) =>
  synth(options)['.claude/settings.json']

test('defaults', () => {
  expect(synth()).toMatchSnapshot()
})

describe('settings', () => {
  test('are written as given', () => {
    expect(
      settings({
        settings: {
          permissions: { deny: ['Read(./.env)'] },
          env: { BASH_DEFAULT_TIMEOUT_MS: '60000' },
        },
      }),
    ).toMatchSnapshot()
  })

  test('declare no policy of their own', () => {
    expect(Object.keys(settings()).sort()).toEqual(['$schema', '//'])
  })

  test('are not shared with the options', () => {
    const options = { settings: { permissions: { allow: ['Bash(ls)'] } } }

    new Claude(
      new Project({ name: 'test-project' }),
      options,
    ).settings.permissions?.allow?.push('Bash(rm:*)')

    expect(options.settings.permissions.allow).toEqual(['Bash(ls)'])
  })
})

describe('schema', () => {
  test('points editors at the published schema', () => {
    expect(settings()['$schema']).toBe(
      'https://json.schemastore.org/claude-code-settings.json',
    )
  })

  test('can be left out', () => {
    expect(settings({ schema: false })).not.toHaveProperty('$schema')
  })

  test('yields to the one in the settings', () => {
    expect(
      settings({ settings: { $schema: 'https://example.com/schema.json' } })[
        '$schema'
      ],
    ).toBe('https://example.com/schema.json')
  })
})

describe('marker', () => {
  test('annotates the file as generated', () => {
    expect(settings()['//']).toMatch(/^~~ Generated by projen\./)
  })
})

describe('ignore file', () => {
  const denyByDefault = (options?: ClaudeOptions) => {
    const project = new Project({
      name: 'test-project',
      gitIgnoreOptions: {
        ignorePatterns: ['.*', '.claude/private.json'],
      },
    })

    new Claude(project, options)

    return project
  }

  const patterns = (project: Project): string[] =>
    synthSnapshot(project)['.gitignore'].split('\n')

  test('re-includes the directory a deny-by-default file excludes', () => {
    expect(patterns(denyByDefault())).toEqual(
      expect.arrayContaining(['!/.claude', '!/.claude/settings.json']),
    )
  })

  test('keeps the patterns a project already has under the directory', () => {
    expect(patterns(denyByDefault())).toContain('.claude/private.json')
  })

  test('ignores the personal settings', () => {
    expect(patterns(denyByDefault())).toContain('/.claude/settings.local.json')
  })

  test('can leave the directory alone', () => {
    expect(patterns(denyByDefault({ gitignore: false }))).not.toContain(
      '!/.claude',
    )
  })

  test('ignores the personal settings even then', () => {
    expect(patterns(denyByDefault({ gitignore: false }))).toContain(
      '/.claude/settings.local.json',
    )
  })

  describe('as git reads it', () => {
    const ignored = (project: Project, file: string) => {
      project.synth()

      mkdirSync(path.dirname(path.join(project.outdir, file)), {
        recursive: true,
      })

      if (!existsSync(path.join(project.outdir, file))) {
        writeFileSync(path.join(project.outdir, file), '{}')
      }

      execFileSync('git', ['init', '--quiet'], { cwd: project.outdir })

      try {
        execFileSync('git', ['check-ignore', '--quiet', file], {
          cwd: project.outdir,
        })

        return true
      } catch {
        return false
      }
    }

    test('the settings are tracked', () => {
      expect(ignored(denyByDefault(), '.claude/settings.json')).toBe(false)
    })

    test('the settings are ignored when the directory is left alone', () => {
      expect(
        ignored(denyByDefault({ gitignore: false }), '.claude/settings.json'),
      ).toBe(true)
    })

    test.each([
      '.claude/settings.local.json',
      '.claude/private.json',
      '.claude/.hidden',
      'packages/a/.claude/settings.json',
    ])('%s stays ignored', (file) => {
      expect(ignored(denyByDefault(), file)).toBe(true)
    })
  })
})
