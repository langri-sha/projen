import { describe, expect, test } from '@langri-sha/vitest'
import { Project } from 'projen'
import { synthSnapshot } from 'projen/lib/util/synth'

import { Changesets, type ChangesetsOptions } from './index'

const synth = (options?: ChangesetsOptions) => {
  const project = new Project({
    name: 'test-project',
  })

  new Changesets(project, options)

  return synthSnapshot(project)
}

const config = (options?: ChangesetsOptions) =>
  synth(options)['.changeset/config.json']

test('defaults', () => {
  expect(synth()).toMatchSnapshot()
})

describe('config', () => {
  test('defaults to what changeset init writes', () => {
    expect(config()).toEqual({
      $schema: 'https://unpkg.com/@changesets/config/schema.json',
      '//': expect.stringMatching(/^~~ Generated by projen\./),
      baseBranch: 'main',
      access: 'restricted',
      ignore: [],
      fixed: [],
      linked: [],
      format: 'auto',
      updateInternalDependencies: 'patch',
      commit: false,
      changelog: '@changesets/cli/changelog',
    })
  })

  test('leaves private packages unset', () => {
    expect(config()).not.toHaveProperty('privatePackages')
  })

  test('overrides the defaults key by key', () => {
    expect(
      config({
        config: {
          baseBranch: 'trunk',
          privatePackages: { version: true, tag: true },
        },
      }),
    ).toMatchObject({
      baseBranch: 'trunk',
      access: 'restricted',
      privatePackages: { version: true, tag: true },
    })
  })
})

describe('schema', () => {
  test('points editors at the published schema', () => {
    expect(config()['$schema']).toBe(
      'https://unpkg.com/@changesets/config/schema.json',
    )
  })

  test('can be left out', () => {
    expect(config({ schema: false })).not.toHaveProperty('$schema')
  })

  test('yields to the one in the config', () => {
    expect(
      config({ config: { $schema: 'https://example.com/schema.json' } })[
        '$schema'
      ],
    ).toBe('https://example.com/schema.json')
  })
})

describe('gitignore', () => {
  test('re-includes the directory', () => {
    expect(synth()['.gitignore']).toContain('!/.changeset\n')
  })

  test('can be left alone', () => {
    expect(synth({ gitignore: false })['.gitignore']).not.toContain(
      '!/.changeset\n',
    )
  })
})
